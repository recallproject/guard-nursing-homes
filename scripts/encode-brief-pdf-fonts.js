#!/usr/bin/env node
/**
 * Encode the Latin-1 Liberation Sans subset TTFs as base64 JS modules.
 *
 * Usage: node scripts/encode-brief-pdf-fonts.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const fontDir = path.join(root, 'src/assets/fonts');
const outPath = path.join(root, 'src/utils/briefPdfFontData.js');

function load(name) {
  const file = path.join(fontDir, name);
  const b64 = fs.readFileSync(file).toString('base64');
  return { bytes: fs.statSync(file).size, b64 };
}

const regular = load('LiberationSans-Regular.latin.ttf');
const bold = load('LiberationSans-Bold.latin.ttf');

const contents = `/* Auto-generated by scripts/encode-brief-pdf-fonts.js — do not edit by hand.
 * Latin-1 subset of Liberation Sans (SIL OFL 1.1). See src/assets/fonts/LICENSE-LiberationSans.txt
 */
export const LIBERATION_SANS_REGULAR_B64 = '${regular.b64}';
export const LIBERATION_SANS_BOLD_B64 = '${bold.b64}';
`;

fs.writeFileSync(outPath, contents);
console.log(`Wrote ${path.relative(root, outPath)} regular=${regular.bytes}B bold=${bold.bytes}B`);
